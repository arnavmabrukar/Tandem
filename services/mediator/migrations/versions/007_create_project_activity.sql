-- Create the activity storage and sequence counter together.
BEGIN;

-- Each project gets its own event counter.
-- The backend will increment this inside the task transaction.
ALTER TABLE public.projects
    ADD COLUMN activity_sequence BIGINT NOT NULL DEFAULT 0
        CHECK (activity_sequence >= 0);

CREATE TABLE public.project_activity (
    -- Permanent identifier for this event.
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    -- Every event belongs to one project.
    project_id UUID NOT NULL
        REFERENCES public.projects(id) ON DELETE CASCADE,

    -- Event order within this project: 1, 2, 3, ...
    -- The backend supplies this from the project's counter.
    sequence BIGINT NOT NULL CHECK (sequence >= 1),

    -- Optional because future events may concern the whole project.
    task_id UUID,

    -- Record the authenticated human responsible for this event.
    -- Agent-generated events will need a separate actor design later.
    actor_user_id UUID NOT NULL
        REFERENCES public.users(id) ON DELETE RESTRICT,

    -- Preserve the name displayed when the event happened.
    -- A later profile rename will not rewrite this historical label.
    actor_name TEXT NOT NULL
        CHECK (length(trim(actor_name)) > 0),

    -- Initially we record these two task lifecycle events.
    kind TEXT NOT NULL
        CHECK (kind IN ('task_created', 'task_cancelled')),

    -- Human-readable description generated by the backend.
    text TEXT NOT NULL
        CHECK (length(trim(text)) > 0),

    -- Record the actual insertion time, including after lock waits.
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    -- Prevent duplicate sequence numbers within a project.
    -- This also creates an index for reading its timeline in order.
    CONSTRAINT project_activity_sequence_unique
        UNIQUE (project_id, sequence),

    -- If a task is referenced, it must belong to this project.
    -- This uses the composite unique constraint added by migration 006.
    -- NO ACTION prevents leaving dangling references after deletion.
    CONSTRAINT project_activity_task_fk
        FOREIGN KEY (project_id, task_id)
        REFERENCES public.tasks (project_id, id)
        ON DELETE NO ACTION
);

-- Support lookups by task, including foreign-key deletion checks.
CREATE INDEX project_activity_task_idx
    ON public.project_activity (project_id, task_id);

COMMIT;